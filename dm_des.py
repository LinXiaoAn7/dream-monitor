def _perm(bits, table):
    return [bits[i - 1] for i in table]


def _b2i(bits):
    v = 0
    for b in bits:
        v = (v << 1) | b
    return v


def _i2b(v, n):
    return [(v >> (n - 1 - i)) & 1 for i in range(n)]


def _subkeys(key8: bytes):
    k = _perm(_i2b(int.from_bytes(key8, "big"), 64), _PC1)
    c, d = k[:28], k[28:]
    out = []
    for s in _SH:
        c = c[s:] + c[:s]
        d = d[s:] + d[:s]
        out.append(_perm(c + d, _PC2))
    return out


def des_block(block8: bytes, key8: bytes = KEY, decrypt: bool = False) -> bytes:
    ks = _subkeys(key8)
    if decrypt:
        ks = ks[::-1]
    bits = _perm(_i2b(int.from_bytes(block8, "big"), 64), _IP)
    left, right = bits[:32], bits[32:]
    for k in ks:
        x = [a ^ b for a, b in zip(_perm(right, _E), k)]
        s = []
        for i in range(8):
            six = x[i * 6:(i + 1) * 6]
            row = (six[0] << 1) | six[5]
            col = (six[1] << 3) | (six[2] << 2) | (six[3] << 1) | six[4]
            s += _i2b(_SBOX[i][row * 16 + col], 4)
        left, right = right, [a ^ b for a, b in zip(left, _perm(s, _P))]
    return _b2i(_perm(right + left, _FP)).to_bytes(8, "big")


def des_ecb(data: bytes, key: bytes = KEY) -> bytes:
    """PKCS5 填充后做 DES-ECB（与 App 完全一致）。"""
    n = 8 - len(data) % 8
    data = data + bytes([n]) * n
    return b"".join(des_block(data[i:i + 8], key) for i in range(0, len(data), 8))


def encrypt_password(password: str) -> str:
    """把明文密码变成服务端要的那串 32 位大写十六进制。"""
    return des_ecb(password.encode("utf-8")).hex().upper()


def decrypt_password(cipher_hex: str) -> str:
    raw = bytes.fromhex(cipher_hex)
    plain = b"".join(des_block(raw[i:i + 8], KEY, decrypt=True) for i in range(0, len(raw), 8))
    n = plain[-1] if plain else 0
    if 1 <= n <= 8:
        plain = plain[:-n]
    return plain.decode("utf-8", "replace")


